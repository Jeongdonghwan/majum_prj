const hash = (s: string) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; } return h; };

export function angleOf(term: string, place: string, seed: string) {
  const a = ANGLES.find((x) => x.re.test(term));
  if (!a) return null;
  const h = hash(seed);
  const n = a.p.length;
  const paras = [a.p[h % n], a.p[(h % n + 1 + (h >> 4) % (n - 1)) % n]].map((f) => f(place, term));
  return { key: a.key, heading: a.h[h % a.h.length](place, term), paras, faq: a.q.map((x) => ({ q: x.q(place, term), a: x.a(place, term) })) };
}
